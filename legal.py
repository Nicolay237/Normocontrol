def requisites():
    env = lambda k: os.environ.get(k, "").strip()
    return {
        "name": env("LEGAL_NAME") or "[укажите ФИО: LEGAL_NAME]",
        "inn": env("LEGAL_INN") or "[укажите ИНН: LEGAL_INN]",
        "email": env("CONTACT_EMAIL") or "[укажите email: CONTACT_EMAIL]",
        "phone": env("CONTACT_PHONE"),
        "site": (os.environ.get("SITE_URL") or "https://normocontrol.site").rstrip("/"),
    }


def missing():
    """Каких реквизитов не хватает — для предупреждения в /admin."""
